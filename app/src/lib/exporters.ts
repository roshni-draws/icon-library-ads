import type { LibData } from './iconLibrary';
import { DEEP_TEAL, type SchemeKey } from './library';
import { LOTTIE_SCHEMES, lottieDir, lottieUrl, tintedLottie, variantLottie, type PrimaryData, type Variant } from './primary';
import { bakeSvg, fmtRatio, pairFor, resolveBg, tileContrast } from './tile';

/**
 * Export with a tile colour: `bg` (preset id or #RRGGBB) and the scheme the page shows. SVGs are baked with that
 * scheme's values; each Lottie scheme file gets the pair of its own scheme (a custom colour is the same in all 6).
 * null = the theme default (files as they are in the library).
 */
export interface ExportTint { bg: string; scheme: SchemeKey }
export const primarySvgOut = (svg: string, t: ExportTint | null | undefined) => (t ? bakeSvg(svg, resolveBg(t.bg, t.scheme), t.scheme) : svg);
/** One Lottie scheme file as text: as-is, or recoloured with the tint's pair for that scheme. */
export async function primaryLottieOut(p: PrimaryData, name: string, sc: SchemeKey, v: Variant, t: ExportTint | null | undefined): Promise<string> {
  if (!t) {
    const r = await fetch(lottieUrl(name, sc, v), { cache: 'no-store' });
    if (!r.ok) throw new Error(`HTTP ${r.status}`);
    return r.text();
  }
  const { tile, ink } = pairFor(t.bg, sc);
  return JSON.stringify(await tintedLottie(p, name, sc, v, tile, ink));
}
/** README section on the tile colour of a tinted export. */
function tintNote(t: ExportTint): string {
  const c = resolveBg(t.bg, t.scheme);
  const k = tileContrast(c, t.scheme);
  const rows = LOTTIE_SCHEMES.map((sc) => { const x = resolveBg(t.bg, sc); return `  ${sc.padEnd(24)} tile ${x.tile}  ink ${x.ink}  ink/tile ${fmtRatio(tileContrast(x, sc).inkTile)}`; }).join('\n');
  return `
Tile colour
-----------
Exported with the tile colour "${c.label}"${c.tileRole ? ` (tile = ${c.tileRole}, ink = ${c.inkRole})` : ' (custom; ink chosen automatically: DS near-black or white, whichever contrasts more)'}.
The light fill and the green accent keep their roles (tertiaryFixed, onPrimaryFixedVariant).
  svg/, svg-stroke/            values of the ${t.scheme} scheme baked in: tile ${c.tile}, ink ${c.ink} (ink/tile ${fmtRatio(k.inkTile)}).
                               ${c.tileRole ? `The class rules use var(--antz-${c.tileRole.replace(/[A-Z]/g, (m) => '-' + m.toLowerCase())}, …) so an inlined SVG still follows the theme.` : 'The tile and ink class rules are plain hex.'}
  lottie/, lottie-stroke/      each scheme file recoloured with ${c.tileRole ? 'that scheme\'s pair' : 'the same pair'}:
${rows}
`;
}

/** One downloadable file, as in the Previewer's exporters. */
export interface ExportFile { name: string; mime: string; body: string | Blob }

const STAMP = 'Generated by ANTZ Icon Builder from the ANTZ Rounded library (24 x 24, line = 2px round strokes, filled = solid with cut-outs, currentColor).';

const innerOf = (svg: string) => svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').trim();
/** Root presentation attributes of a library svg (fill, stroke, ...), carried onto the <symbol>. */
function rootPaint(svg: string): string {
  const open = /<svg\b([^>]*)>/.exec(svg)?.[1] ?? '';
  return [...open.matchAll(/\s(fill|stroke|stroke-width|stroke-linecap|stroke-linejoin|fill-rule)="([^"]*)"/g)].map((m) => ` ${m[1]}="${m[2]}"`).join('');
}
/** Mask ids get the symbol's prefix so symbols in one sprite never clash. */
function scopeIds(inner: string, prefix: string): string {
  const ids = [...inner.matchAll(/\sid="([^"]+)"/g)].map((m) => m[1]);
  for (const id of ids) {
    const esc = id.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    inner = inner.replace(new RegExp(`id="${esc}"`, 'g'), `id="${prefix}${id}"`).replace(new RegExp(`url\\(#${esc}\\)`, 'g'), `url(#${prefix}${id})`);
  }
  return inner;
}

/** SVG sprite for one style: <symbol id="antz-<name>"> per drawn icon. Use: <svg><use href="antz-icons-line.svg#antz-egg"/></svg>. */
export function exportSprite(lib: LibData, style: 'line' | 'filled'): ExportFile {
  const svgs = lib.svgs[style];
  const names = lib.index.icons.map((i) => i.name).filter((n) => svgs[n]);
  const symbols = names.map((n) => `  <symbol id="antz-${n}" viewBox="0 0 24 24"${rootPaint(svgs[n])}>\n    ${scopeIds(innerOf(svgs[n]), `antz-${n}-`).replace(/\n\s*/g, '\n    ')}\n  </symbol>`);
  const body = `<svg xmlns="http://www.w3.org/2000/svg" style="display:none">\n  <!-- ${STAMP} ${style}: ${names.length} icons. -->\n${symbols.join('\n')}\n</svg>\n`;
  return { name: `antz-icons-${style}.svg`, mime: 'image/svg+xml', body };
}

export function exportIndex(lib: LibData): ExportFile {
  return { name: 'index.json', mime: 'application/json', body: JSON.stringify(lib.index, null, 2) + '\n' };
}

