/** Fetches every present scheme file of one icon into `lottie/<scheme>/<name>.json`; records the missing ones. */
async function packLottie(zip: import('jszip'), p: PrimaryData, name: string, missing: string[]) {
  for (const sc of LOTTIE_SCHEMES) {
    const path = `lottie/${sc}/${name}.json`;
    if (!p.lottie[name]?.[sc]) { missing.push(path); continue; }
    const r = await fetch(lottieUrl(name, sc), { cache: 'no-store' });
    if (!r.ok) { missing.push(path); continue; }
    zip.file(path, await r.text());
  }
}

/** ZIP of the Primary icons: svg/, lottie/<scheme>/ (6 schemes), index.json and a README with web, React Native and Flutter usage. */
export async function exportPrimaryZip(p: PrimaryData, onProgress?: (msg: string) => void): Promise<ExportFile> {
  if (!p.index.icons.length) throw new Error('there are no Primary icons yet');
  const { default: JSZip } = await import('jszip');
  const zip = new JSZip();
  const missing: string[] = [];
  const icons = [...p.index.icons].sort((a, b) => (a.order ?? 0) - (b.order ?? 0));
  let n = 0;
  for (const i of icons) {
    if (p.svgs[i.name]) zip.file(`svg/${i.name}.svg`, p.svgs[i.name]); else missing.push(`svg/${i.name}.svg`);
    await packLottie(zip, p, i.name, missing);
    onProgress?.(`Packing ${++n} of ${icons.length} Primary icons`);
  }
  zip.file('index.json', JSON.stringify({ ...p.index, icons }, null, 2) + '\n');
  zip.file('README.txt', PRIMARY_README(icons.length, missing));
  const blob = await zip.generateAsync({ type: 'blob', compression: 'DEFLATE' });
  return { name: 'antz-primary-icons.zip', mime: 'application/zip', body: blob };
}

/** ZIP of one Primary icon's Lottie files: lottie/<scheme>/<name>.json for each of the 6 schemes present. */
export async function exportPrimaryLottieZip(p: PrimaryData, name: string): Promise<ExportFile> {
  const { default: JSZip } = await import('jszip');
  const zip = new JSZip();
  const missing: string[] = [];
  await packLottie(zip, p, name, missing);
  if (missing.length === LOTTIE_SCHEMES.length) throw new Error(`no Lottie files for ${name}`);
  const blob = await zip.generateAsync({ type: 'blob', compression: 'DEFLATE' });
  return { name: `${name}-lottie.zip`, mime: 'application/zip', body: blob };
}

export function download(f: ExportFile) {
  const blob = f.body instanceof Blob ? f.body : new Blob([f.body], { type: f.mime });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = f.name;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
