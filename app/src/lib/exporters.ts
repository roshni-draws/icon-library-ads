/**
 * Fetches every present scheme file of one icon into `lottie/<scheme>/<name>.json` (or `lottie-stroke/…` for the
 * stroke variant); records the missing ones.
 */
async function packLottie(zip: import('jszip'), p: PrimaryData, name: string, missing: string[], v: Variant = 'filled', tint?: ExportTint | null) {
  const has = variantLottie(p, name, v);
  for (const sc of LOTTIE_SCHEMES) {
    const path = `${lottieDir(v)}/${sc}/${name}.json`;
    if (!has[sc]) { missing.push(path); continue; }
    try { zip.file(path, await primaryLottieOut(p, name, sc, v, tint)); } catch { missing.push(path); }
  }
}

/**
 * ZIP of the Primary icons: svg/, lottie/<scheme>/ (6 schemes), the stroke variant in svg-stroke/ and
 * lottie-stroke/<scheme>/ (for icons that have one), index.json and a README with web, React Native and Flutter usage.
 */
export async function exportPrimaryZip(p: PrimaryData, onProgress?: (msg: string) => void, tint?: ExportTint | null): Promise<ExportFile> {
  if (!p.index.icons.length) throw new Error('there are no Primary icons yet');
  const { default: JSZip } = await import('jszip');
  const zip = new JSZip();
  const missing: string[] = [];
  const icons = [...p.index.icons].sort((a, b) => (a.order ?? 0) - (b.order ?? 0));
  let n = 0, strokeN = 0;
  for (const i of icons) {
    if (p.svgs[i.name]) zip.file(`svg/${i.name}.svg`, primarySvgOut(p.svgs[i.name], tint)); else missing.push(`svg/${i.name}.svg`);
    await packLottie(zip, p, i.name, missing, 'filled', tint);
    // Stroke files are optional: an icon without any is not listed as missing; a partial set lists its gaps.
    const sSvg = p.svgsStroke?.[i.name];
    const sLot = Object.values(variantLottie(p, i.name, 'stroke')).some(Boolean);
    if (sSvg || sLot) {
      strokeN++;
      if (sSvg) zip.file(`svg-stroke/${i.name}.svg`, primarySvgOut(sSvg, tint)); else missing.push(`svg-stroke/${i.name}.svg`);
      await packLottie(zip, p, i.name, missing, 'stroke', tint);
    }
    onProgress?.(`Packing ${++n} of ${icons.length} Primary icons`);
  }
  zip.file('index.json', JSON.stringify({ ...p.index, icons }, null, 2) + '\n');
  zip.file('README.txt', PRIMARY_README(icons.length, strokeN, missing, tint));
  const blob = await zip.generateAsync({ type: 'blob', compression: 'DEFLATE' });
  return { name: tint ? `antz-primary-icons-${tint.bg.replace('#', '')}.zip` : 'antz-primary-icons.zip', mime: 'application/zip', body: blob };
}

/**
 * ZIP of one Primary icon's Lottie files: lottie/<scheme>/<name>.json (or lottie-stroke/<scheme>/<name>.json for the
 * stroke variant) for each of the 6 schemes present.
 */
export async function exportPrimaryLottieZip(p: PrimaryData, name: string, v: Variant = 'filled', tint?: ExportTint | null): Promise<ExportFile> {
  const { default: JSZip } = await import('jszip');
  const zip = new JSZip();
  const missing: string[] = [];
  await packLottie(zip, p, name, missing, v, tint);
  if (missing.length === LOTTIE_SCHEMES.length) throw new Error(`no ${v === 'stroke' ? 'stroke ' : ''}Lottie files for ${name}`);
  const blob = await zip.generateAsync({ type: 'blob', compression: 'DEFLATE' });
  return { name: `${name}-${v === 'stroke' ? 'stroke-' : ''}lottie${tint ? `-${tint.bg.replace('#', '')}` : ''}.zip`, mime: 'application/zip', body: blob };
}

export function download(f: ExportFile) {
  const blob = f.body instanceof Blob ? f.body : new Blob([f.body], { type: f.mime });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = f.name;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
